import fs from 'node:fs';
import assert from 'node:assert/strict';
import YAML from 'yaml';
const w=YAML.parse(fs.readFileSync('.github/workflows/profile-art.yml','utf8'));
assert.deepEqual(w.on.push.branches,['master']);
assert.ok('workflow_dispatch' in w.on);assert.equal(w.on.schedule.length,1);
assert.equal(w.permissions.contents,'write');
const steps=w.jobs.generate.steps;
assert.equal(steps.at(-1).with.publish_branch,'output');
assert.ok(steps.every(s=>!s['continue-on-error']&&!s.if));
for(const s of steps.filter(s=>s.uses))assert.match(s.uses,/@[0-9a-f]{40}$/);
assert.equal(steps[1].with.outputs.trim().split('\n').length,1);
assert.ok(!steps.find(s=>s.run)?.run.includes('--preview'));
const themes=JSON.parse(fs.readFileSync('config/city-themes.json'));
assert.deepEqual(themes.map(t=>t.fileName),['city-light.svg']);
const readme=fs.readFileSync('README.md','utf8');
assert.ok(!readme.includes('prefers-color-scheme'));
assert.ok(readme.includes('prefers-reduced-motion: reduce'));
assert.ok(readme.includes('city-mobile.svg'));
for(const forbidden of ['2004','September 14','years old','[link]','komarev','trophy','visitcount'])assert.ok(!readme.includes(forbidden));
console.log('PASS: fixed-light README, motion fallback, mobile image, daily/master/manual workflow and last-step-only publishing.');
